const variants: string[] = [], resultVariants: string[] = [], resultMatches: string[] = [];
for (const [op, def] of Object.entries(schema.operations)) {
  const name = pascal(op);
  const fields = Object.entries(def.request.fields).map(([k,v]) => {
    const optional = typeof v !== "string" && "optional" in v;
    return `${optional ? '        #[serde(default, skip_serializing_if = "Option::is_none")]\n' : ''}        ${k}: ${rust(v,name+pascal(k),true)},`;
  });
  variants.push(`    #[serde(rename = ${JSON.stringify(op)})]\n    ${name} {\n${fields.join("\n")}\n    },`);
  rust(def.result, name+"Result", false);
  resultVariants.push(`    ${name}(${name}Result),`);
  resultMatches.push(`            Self::${name} { .. } => PrimitiveResult::${name}(serde_json::from_value(value)?),`);
}

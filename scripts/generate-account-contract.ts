const root = new URL("../", import.meta.url);
type Schema = string | { fields: Record<string, Schema> } | { optional: Schema } | { array: Schema } | { enum: string[] } | { union: Schema[] };
const schema = JSON.parse(readFileSync(new URL("packages/accounts/schema/primitives.json", root), "utf8")) as {
  types: Record<string, Schema>; operations: Record<string, { request: { fields: Record<string, Schema> }; result: Schema }>;
};
const pascal = (s: string) => s.split(/[._]/).map(p => p[0]!.toUpperCase() + p.slice(1)).join("");
function ts(s: Schema): string {
  if (typeof s === "string") return (s === "integer" || s === "file_size") ? "number" : s === "nonempty" ? "string" : s;
  if ("optional" in s) return `(${ts(s.optional)}) | null`;
  if ("array" in s) return `Array<${ts(s.array)}>`;
  if ("enum" in s) return s.enum.map(v => JSON.stringify(v)).join(" | ");
  if ("union" in s) return s.union.map(ts).join(" | ");
  return `{ ${Object.entries(s.fields).map(([k,v]) => `${k}${typeof v !== "string" && "optional" in v ? "?" : ""}: ${ts(v)}`).join("; ")} }`;
}

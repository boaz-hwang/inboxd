const declarations: string[] = [];
function rust(s: Schema, name: string, strict: boolean): string {
  if (typeof s === "string") return ({string:"String", nonempty:"String", number:"f64", integer:"SafeInteger", file_size:"SafeInteger", boolean:"bool"} as Record<string,string>)[s] ?? s;
  if ("optional" in s) return `Option<${rust(s.optional,name,strict)}>`;
  if ("array" in s) return `Vec<${rust(s.array,name,strict)}>`;
  const derive = '#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]\n';
  if ("enum" in s) {
    declarations.push(`${derive}pub(crate) enum ${name} {\n${s.enum.map(v => `    #[serde(rename = ${JSON.stringify(v)})]\n    ${pascal(v)},`).join("\n")}\n}`);
  } else if ("union" in s) {
    const variants = s.union.map((v,i) => `    V${i}(${rust(v,`${name}V${i}`,strict)}),`);
    declarations.push(`${derive}#[serde(untagged)]\npub(crate) enum ${name} {\n${variants.join("\n")}\n}`);
  } else {
    const fields = Object.entries(s.fields).map(([k,v]) => {
      const optional = typeof v !== "string" && "optional" in v;
      return `${optional ? '    #[serde(default, skip_serializing_if = "Option::is_none")]\n' : ''}    pub(crate) ${k === "type" ? "r#type" : k}: ${rust(v, name+pascal(k), strict)},`;
    });
    declarations.push(`${derive}${strict ? '#[serde(deny_unknown_fields)]\n' : ''}pub(crate) struct ${name} {\n${fields.join("\n")}\n}`);
  }
  return name;
}
